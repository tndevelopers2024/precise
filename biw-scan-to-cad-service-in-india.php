        document.addEventListener('DOMContentLoaded', function () {
            const track = document.getElementById('wcdTrack');
            const prevBtn = document.getElementById('wcdPrevBtn');
            const nextBtn = document.getElementById('wcdNextBtn');

            if (!track || !prevBtn || !nextBtn) return;

            const scrollStep = 220; // 190px card width + 16px gap + buffer

            prevBtn.addEventListener('click', function () {
                track.scrollBy({ left: -scrollStep, behavior: 'smooth' });
            });

            nextBtn.addEventListener('click', function () {
                track.scrollBy({ left: scrollStep, behavior: 'smooth' });
            });

            // Mouse drag scrolling for smooth desktop exploration
            let isDown = false;
            let startX;
            let scrollLeft;

            track.addEventListener('mousedown', (e) => {
                isDown = true;
                startX = e.pageX - track.offsetLeft;
                scrollLeft = track.scrollLeft;
            });

            track.addEventListener('mouseleave', () => {
                isDown = false;
            });

            track.addEventListener('mouseup', () => {
                isDown = false;
            });

            track.addEventListener('mousemove', (e) => {
                if (!isDown) return;
                e.preventDefault();
                const x = e.pageX - track.offsetLeft;
                const walk = (x - startX) * 1.5;
                track.scrollLeft = scrollLeft - walk;
            });
        });

