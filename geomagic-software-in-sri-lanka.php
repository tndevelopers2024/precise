    <script>
        document.addEventListener("DOMContentLoaded", () => {
            const counters = document.querySelectorAll('.gsisl-counter');
            const animationDuration = 2000; // Complete animation in 2 seconds

            const animateCounters = () => {
                let startTimestamp = null;
                const step = (timestamp) => {
                    if (!startTimestamp) startTimestamp = timestamp;
                    const progress = Math.min((timestamp - startTimestamp) / animationDuration, 1);
                    
                    counters.forEach(counter => {
                        const target = +counter.getAttribute('data-target');
                        counter.innerText = Math.floor(progress * target);
                    });
                    
                    if (progress < 1) {
                        window.requestAnimationFrame(step);
                    } else {
                        // Ensure it finishes on the exact targets
                        counters.forEach(counter => {
                            counter.innerText = counter.getAttribute('data-target');
                        });
                    }
                };
                window.requestAnimationFrame(step);
            };

            const observer = new IntersectionObserver((entries, obs) => {
                let triggered = false;
                entries.forEach(entry => {
                    if (entry.isIntersecting && !triggered) {
                        triggered = true;
                        animateCounters();
                        obs.disconnect(); // Stop observing once triggered
                    }
                });
            }, { threshold: 0.5 });
            
            // Observe the parent container instead of individual counters to sync them
            const statsRow = document.querySelector('.hero-stats-row');
            if (statsRow) observer.observe(statsRow);
        });
    </script>
